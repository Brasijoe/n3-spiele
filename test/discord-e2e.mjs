// Läuft gegen einen lokalen Worker (test/reset.sh) mit DISCORD_PUBLIC_KEY aus /tmp/dk.json und DISCORD_GUILD_ID=g1.
import fs from 'node:fs';
import assert from 'node:assert/strict';
const { priv } = JSON.parse(fs.readFileSync('/tmp/dk.json', 'utf8'));
const key = await crypto.subtle.importKey('pkcs8', Buffer.from(priv, 'base64'), 'Ed25519', false, ['sign']);
const post = async (obj, bad) => {
  const body = JSON.stringify(obj), ts = String(Date.now());
  const sig = Buffer.from(await crypto.subtle.sign('Ed25519', key, new TextEncoder().encode(ts + body))).toString('hex');
  const r = await fetch('http://localhost:8799/api/discord/interactions', { method: 'POST', headers: { 'x-signature-ed25519': bad ? '00'.repeat(64) : sig, 'x-signature-timestamp': ts }, body });
  return { status: r.status, json: r.status === 200 ? await r.json() : null };
};
const user = (id, name) => ({ member: { user: { id, username: name } } });
assert.equal((await post({ type: 1 }, true)).status, 401);
assert.equal((await post({ type: 1 })).json.type, 1);
let r = await post({ type: 2, guild_id: 'g1', ...user('111', 'Hans'), data: { name: 'party', options: [{ name: 'spiel', value: '295947|Cascadia|2021' }, { name: 'plaetze', value: 3 }, { name: 'datum', value: '2099-01-05' }] } });
assert.equal(r.json.type, 4); const e = r.json.data.embeds[0];
assert.equal(e.title, '🎲 Cascadia (2021)'); console.log('party ok:', e.fields.map((f) => f.name + '=' + f.value.replace(/\n/g, '|')).join(' ; '));
const pid = r.json.data.components[0].components[0].custom_id.split(':')[1];
const click = (act, id, name) => post({ type: 3, guild_id: 'g1', ...user(id, name), data: { custom_id: act + ':' + pid } });
r = await click('join', '222', 'Anna'); assert.equal(r.json.type, 7);
r = await click('join', '333', 'Bernd'); assert.equal(r.json.type, 7);
r = await click('join', '444', 'Carl'); assert.match(r.json.data.content, /voll/);
r = await click('leave', '222', 'Anna'); assert.equal(r.json.type, 7);
r = await click('join', '444', 'Carl'); assert.equal(r.json.type, 7);
r = await click('log', '222', 'Anna'); assert.match(r.json.data.content, /Ersteller/);
r = await click('log', '111', 'Hans'); assert.match(r.json.data.content, /Termin/);
console.log('log before date blocked ok');
r = await click('manage', '222', 'Anna'); assert.match(r.json.data.content, /Ersteller/);
r = await click('manage', '111', 'Hans'); assert.equal(r.json.data.flags, 64); assert.equal(r.json.data.components[0].components.length, 3);
r = await click('edit', '222', 'Anna'); assert.match(r.json.data.content, /Ersteller/);
r = await post({ type: 3, guild_id: 'g1', member: { permissions: '32', user: { id: '999', username: 'Mod' } }, data: { custom_id: 'manage:' + pid } }); assert.equal(r.json.data.flags, 64); console.log('mod can manage ok');
r = await click('edit', '111', 'Hans'); assert.equal(r.json.type, 9); assert.equal(r.json.data.components.length, 5);
const sub = (vals, u = user('111', 'Hans')) => post({ type: 5, guild_id: 'g1', ...u, data: { custom_id: 'edit:' + pid, components: Object.entries(vals).map(([k, v]) => ({ type: 1, components: [{ type: 4, custom_id: k, value: v }] })) } });
r = await sub({ spiel: 'X', datum: '24.11.2026', uhrzeit: '19:30', plaetze: '5' }, user('222', 'Anna')); assert.match(r.json.data.content, /Ersteller/);
r = await sub({ spiel: 'Cascadia', datum: '24.11.2026', uhrzeit: '19:30', plaetze: '2', hinweis: 'x' }); assert.match(r.json.data.content, /mindestens 3/);
r = await sub({ spiel: 'Azul', datum: '24.11.2026', uhrzeit: '19:30', plaetze: '5', hinweis: 'neu' }); assert.equal(r.json.type, 7);
assert.match(r.json.data.content, /Gespeichert/);
const pr = (await (await fetch('http://localhost:8799/api/parties')).json())[0]; assert.equal(pr.game, 'Azul'); assert.equal(pr.seats, 5); assert.equal(pr.time, '19:30'); console.log('edit ok');
r = await click('cancel', '222', 'Anna'); assert.match(r.json.data.content, /Ersteller/);
r = await click('cancel', '111', 'Hans'); assert.equal(r.json.data.components[0].components[0].custom_id, 'cancelyes:' + pid);
r = await click('cancelno', '111', 'Hans'); assert.equal(r.json.data.components[0].components.length, 3);
r = await click('cancelyes', '111', 'Hans'); assert.match(r.json.data.content, /storniert/);
assert.equal((await (await fetch('http://localhost:8799/api/parties')).json()).length, 0);
console.log('cancel ok'); process.exit(0);
