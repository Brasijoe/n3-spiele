// Webseite -> Discord: Mock der Discord-API auf :8801, Worker (test/reset.sh) mit DISCORD_API_BASE=http://localhost:8801.
import http from 'node:http';
import assert from 'node:assert/strict';
const calls = [];
http.createServer((req, res) => { let b = ''; req.on('data', (c) => (b += c)); req.on('end', () => { calls.push({ m: req.method, u: req.url, auth: req.headers.authorization, b: b ? JSON.parse(b) : null }); res.setHeader('content-type', 'application/json'); res.end(JSON.stringify({ id: 'm1' })); }); }).listen(8801);
const W = 'http://localhost:8799/api', H = { 'x-member-code': 'ABCD2345', 'content-type': 'application/json' };
const wait = () => new Promise((r) => setTimeout(r, 700));
let r = await (await fetch(W + '/parties', { method: 'POST', headers: H, body: JSON.stringify({ game: 'Azul', gameId: 1084, date: '2099-01-05', time: '18:00', seats: 4, host: 'Anna' }) })).json();
await wait();
assert.equal(calls[0].m, 'POST'); assert.equal(calls[0].u, '/channels/CH1/messages'); assert.equal(calls[0].auth, 'Bot TESTTOKEN');
assert.equal(calls[0].b.embeds[0].title, '🎲 Azul'); console.log('announce ok');
await fetch(W + `/parties/${r.id}/join`, { method: 'POST', headers: H, body: JSON.stringify({ key: 'abc123xy', name: 'Bob' }) }); await wait();
const j = calls.at(-1); assert.equal(j.m, 'PATCH'); assert.equal(j.u, '/channels/CH1/messages/m1');
assert.match(JSON.stringify(j.b.embeds), /Bob/); console.log('join sync ok');
await fetch(W + `/parties/${r.id}`, { method: 'DELETE', headers: { 'x-admin-token': 'test-admin-pw' } }); await wait();
assert.match(calls.at(-1).b.content, /storniert/); console.log('delete sync ok');
const before = calls.filter((c) => c.m === 'POST').length;
for (let i = 0; i < 7; i++) await fetch(W + '/parties', { method: 'POST', headers: H, body: JSON.stringify({ game: 'G' + i, date: '2099-01-05', seats: 4, host: 'Spam' }) });
await wait();
const posted = calls.filter((c) => c.m === 'POST').length - before;
assert.equal(posted + before, 5, 'Obergrenze 5 pro Stunde'); console.log('spam limit ok, posts total', posted + before);
process.exit(0);
